package com.daxz.weekalarm;

import java.time.LocalDate;

/**
 * 二十四节气（v1.51.2）。
 *
 * <p>为什么用查表而不是公式：寿星公式（{@code [Y×0.2422+C]−L}）对个别年份有 ±1 天误差，
 * 而节气错一天就是「霜降」标在 22 号、实际 23 号——日历类 App 这种错最刺眼。
 * 内置 2020–2040 共 21 年、504 个日期，每年 24 个「日」压成 48 个字符，全表 1KB。
 *
 * <p>数据由寿星天文历（sxtwl，精度到秒）按北京时间算出，2026 年霜降 = 10/23、
 * 冬至 = 12/22、小寒 = 1/5，与紫金山天文台公布的一致。
 *
 * <p>超出 2020–2040 返回 {@code null}（不显示），而不是拿公式硬算——
 * 宁可日历上少一个标记，也不要标错一天。2040 年之前需要扩表。
 */
public final class SolarTerm {

    private static final int BASE_YEAR = 2020;

    /** 按公历月份顺序：1 月小寒、大寒，2 月立春、雨水……12 月大雪、冬至。 */
    private static final String[] NAMES = {
            "小寒", "大寒", "立春", "雨水", "惊蛰", "春分", "清明", "谷雨",
            "立夏", "小满", "芒种", "夏至", "小暑", "大暑", "立秋", "处暑",
            "白露", "秋分", "寒露", "霜降", "立冬", "小雪", "大雪", "冬至",
    };

    /**
     * 每年 24 个日期，每个两位数字（01~31），顺序同 {@link #NAMES}。
     *
     * <p>不写成 {@code int[]} 是为了让表在源码里一眼能看出年份对应关系；
     * 解析成本可以忽略（一年最多查 2 次）。
     */
    private static final String[] DAYS = {
            "062004190520041905200521062207220722082307220721",   // 2020
            "052003180520042005210521072207230723082307220721",   // 2021
            "052004190520052005210621072307230723082307220722",   // 2022
            "052004190621052006210621072308230823082408220722",   // 2023
            "062004190520041905200521062207220722082307220621",   // 2024
            "052003180520042005210521072207230723082307220721",   // 2025
            "052004180520052005210521072307230723082307220722",   // 2026
            "052004190621052006210621072308230823082307220722",   // 2027
            "062004190520041905200521062207220722082307220621",   // 2028
            "052003180520042005210521072207230723082307220721",   // 2029
            "052004180520052005210521072307230723082307220722",   // 2030
            "052004190621052006210621072308230823082307220722",   // 2031
            "062004190520041905200521062207220722082307220621",   // 2032
            "052003180520042005210521072207230723082307220721",   // 2033
            "052004180520052005210521072307230723082307220722",   // 2034
            "052004190621052006210621072308230823082307220722",   // 2035
            "062004190520041905200521062207220722082307220621",   // 2036
            "052003180520042005210521072207230723082307220721",   // 2037
            "052004180520052005210521072307230723082307220722",   // 2038
            "052004190621052006210621072308230823082307220722",   // 2039
            "062004190520041905200521062207220722082307220621",   // 2040
    };

    private SolarTerm() {
    }

    /** 这一天是不是节气；是就返回名字（如「霜降」），不是返回 {@code null}。 */
    public static String termOf(LocalDate d) {
        if (d == null) return null;
        int year = d.getYear();
        int idx = year - BASE_YEAR;
        if (idx < 0 || idx >= DAYS.length) return null;

        String row = DAYS[idx];
        int month = d.getMonthValue();
        int day = d.getDayOfMonth();
        int base = (month - 1) * 2;
        for (int k = 0; k < 2; k++) {
            int i = base + k;
            int dd = (row.charAt(i * 2) - '0') * 10 + (row.charAt(i * 2 + 1) - '0');
            if (dd == day) return NAMES[i];
        }
        return null;
    }

    /** 表覆盖的年份范围，给文档和测试用。 */
    public static int firstYear() {
        return BASE_YEAR;
    }

    public static int lastYear() {
        return BASE_YEAR + DAYS.length - 1;
    }
}
